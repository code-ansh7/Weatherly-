class WeatherModel {
  String cityName;
  String temperature;
  String humidity;
  String windSpeed;
  String condition;
  String description;
  String pressure;
  String visibility;

  WeatherModel({
    required this.cityName,
    required this.temperature,
    required this.humidity,
    required this.windSpeed,
    required this.condition,
    required this.description,
    required this.pressure,
    required this.visibility,
  });
}